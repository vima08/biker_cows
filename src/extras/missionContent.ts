export function missionLocation(segment: number, progress: number): MapLocation {
  const mission = MISSIONS[segment], path = mission.path;
  const position = Math.max(0, Math.min(1, progress)) * (path.length - 1);
  const index = Math.min(path.length - 2, Math.floor(position)), t = position - index;
  return { x: path[index][0] + (path[index+1][0] - path[index][0]) * t,
    y: path[index][1] + (path[index+1][1] - path[index][1]) * t, label: mission.title };
}
